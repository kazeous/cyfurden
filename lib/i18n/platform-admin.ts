const catalogues: Record<Locale, PlatformAdminCatalogue> = {
  en: englishPlatformAdminCatalogue,
  vi: vietnamesePlatformAdminCatalogue,
};

export function getPlatformAdminStrings(locale: Locale | string | undefined) {
  return catalogues[parseLocale(locale)];
}

export function platformLocaleTag(locale: Locale) {
  return locale === "vi" ? "vi-VN" : "en-GB";
}

export function formatPlatformNumber(value: number, locale: Locale) {
  return new Intl.NumberFormat(platformLocaleTag(locale)).format(value);
}

export function formatPlatformDateTime(
  value: Date | string | null | undefined,
  locale: Locale,
) {
  if (!value) return getPlatformAdminStrings(locale).common.notAvailable;
  return new Intl.DateTimeFormat(platformLocaleTag(locale), {
    dateStyle: "medium",
    timeStyle: "short",
    timeZone: "Asia/Ho_Chi_Minh",
  }).format(new Date(value));
}

export function formatPlatformBytes(
  value: bigint | number | string,
  locale: Locale,
) {
  const bytes = typeof value === "bigint" ? value : BigInt(value);
  const units = ["B", "KiB", "MiB", "GiB", "TiB"] as const;
  let unitIndex = 0;
  let divisor = BigInt(1);
  while (unitIndex < units.length - 1 && bytes >= divisor * BigInt(1024)) {
    unitIndex += 1;
    divisor *= BigInt(1024);
  }
  const scaled = Number((bytes * BigInt(100)) / divisor) / 100;
  return `${new Intl.NumberFormat(platformLocaleTag(locale), {
    maximumFractionDigits: unitIndex === 0 ? 0 : 2,
  }).format(scaled)} ${units[unitIndex]}`;
}

export function shortPlatformId(value: string, visible = 10) {
  return value.length <= visible + 4
    ? value
    : `${value.slice(0, visible)}…${value.slice(-4)}`;
}
